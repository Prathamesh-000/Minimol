/** Desktop CPU benchmark of two local role engines. No network/mobile claims. */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { cpus, release } from 'node:os';
const loading = {}; const loadStart = performance.now();
import { decodeShard } from '../dist/inference/weightLoader.js';
import { Phone1Engine } from '../dist/inference/phone1Engine.js';
import { Phone2Engine } from '../dist/inference/phone2Engine.js';
import { scalarBackend } from '../dist/inference/matrixMultiply.js';
import { instantiateWasmBackend } from '../dist/inference/wasmBackend.js';
import { generate } from '../dist/inference/generation.js';

const root = new URL('../', import.meta.url), manifest = JSON.parse(await readFile(new URL('public/model/manifest.json', root), 'utf8'));
const arrayBuffer = b => b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength);
const shards = await Promise.all(['phone1', 'phone2'].map(async role => { const start=performance.now();const shard=await decodeShard(role, manifest, arrayBuffer(await readFile(new URL(`public/model/${role}.bin`, root))));loading[role]=performance.now()-start;return shard; }));
const report = { environment: { runtime: process.version, platform: process.platform, architecture: process.arch, osRelease: release(), cpu: cpus()[0]?.model, shardReadVerifyMs: loading, totalReadVerifyMs: performance.now()-loadStart },
  modelId: manifest.model_config.model_id, configHash: manifest.config_sha256,
  shardHashes: Object.fromEntries(Object.entries(manifest.files).map(([role, f]) => [role, f.sha256])),
  scope: 'two local role engines, no transport, not a mobile/browser benchmark',
  prompt: 'Hello', maxNewBytes: 32, temperature: 0, warmups: 2, measuredRuns: 5, backends: [] };
let expected;
for (const variant of ['typescript', 'scalar', 'simd']) {
  const wasm = variant === 'typescript' ? null : arrayBuffer(await readFile(new URL(`public/wasm/matrix-${variant}.wasm`, root)));
  const a = new Phone1Engine(shards[0], wasm ? await instantiateWasmBackend(wasm, 'phone1') : scalarBackend);
  const b = new Phone2Engine(shards[1], wasm ? await instantiateWasmBackend(wasm, 'phone2') : scalarBackend);
  const samples = [];
  for (let run = 0; run < report.warmups + report.measuredRuns; run++) {
    let phone1Ms = 0, phone2Ms = 0, prefillMs = 0; const perPositionMs=[];
    const start = performance.now();
    const result = await generate({
      async reset() { a.reset(); b.reset(); },
      async step(byte, position) {
        const stepStart=performance.now();let before = performance.now(); const hidden = a.step(byte, position); phone1Ms += performance.now() - before;
        before = performance.now(); const result = b.step(hidden, position); phone2Ms += performance.now() - before;
        perPositionMs.push(performance.now()-stepStart);return result.byte;
      },
    }, report.prompt, report.maxNewBytes, {onByte(){if(!prefillMs)prefillMs=performance.now()-start}});
    const elapsedMs = performance.now() - start;
    if (!expected) expected = [...result.generated];
    assert.deepEqual([...result.generated], expected);assert.deepEqual([...result.generated].slice(0,8),[63,119,179,184,253,37,243,172]);
    if (run >= report.warmups) samples.push({ prefillMs, perPositionMs, processMemory: process.memoryUsage(), kvBytesPerRole: a.stats.kvBytes, dataChannelTransferMs: null, elapsedMs, phone1Ms, phone2Ms, generatedBytes: result.generated.length,
      processedPositions: result.processedPositions, generatedBytesPerSecond: result.generated.length * 1000 / elapsedMs });
  }
  const durations = samples.map(s => s.elapsedMs).sort((x, y) => x - y);
  const meanMs = durations.reduce((x, y) => x + y, 0) / durations.length;
  const medianMs = durations[Math.floor(durations.length / 2)];
  report.backends.push({ backend: a.stats.backend, meanMs, medianMs, generatedBytesPerSecondAtMean: 32000 / meanMs, samples });
  console.log(`${a.stats.backend}: mean ${meanMs.toFixed(2)} ms, median ${medianMs.toFixed(2)} ms, ${(32000 / meanMs).toFixed(2)} generated bytes/s (prefill included)`);
  a.dispose(); b.dispose();
}
report.generatedBytes = expected;
await mkdir(new URL('artifacts/reports/', root), { recursive: true });
await writeFile(new URL('artifacts/reports/milestone2-desktop-benchmark.json', root), JSON.stringify(report, null, 2) + '\n');

await writeFile(new URL('artifacts/reports/milestone6-desktop-benchmark.json',root),JSON.stringify(report,null,2)+'\n');
